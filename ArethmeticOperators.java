public class ArethmeticOperators {

    public static void main(String[] args){

        //ArethmeticOperators

            int x;
            int y;
            int result;


            //Addition

        x = 10;
        y = 2;

                result = x + y;
        System.out.println("The result to " + x + " + " + y + " y equals " + result + "!");

        x += y;

        System.out.println("Alternatively, x += y equals " + x + "!");

            //Substraction

        x = 10;
        y = 2;

                result = x - y;
        System.out.println("The result to " + x + " - " + y + " y equals " + result + "!");

        x -= y;

        System.out.println("Alternatively, x -= y equals " + x + "!");


            //Multiplication

        x = 10;
        y = 2;

                result = x * y;
        System.out.println("The result to " + x + " * " + y + " y equals " + result + "!");

        x *= y;

        System.out.println("Alternatively, x *= y equals " + x + "!");


            //Division

        x = 10;
        y = 2;

        result = x / y;
        System.out.println("The result to " + x + " / " + y + " y equals " + result + "!");

        x /= y;

        System.out.println("Alternatively, x /= y equals " + x + "!");

            //Modulus

        x = 10;
        y = 3;

                result = x % y;

        System.out.println("The Modulus of " + x + " to " + y + " y is " + result + "!");

        x %= y;

        System.out.println("Alternatively, x %= y equals " + x + "!");


            //Increment and Decrement Operators

        x = 1;

        x++;

        System.out.println("Instead of x = x + 1, use x++: " + x + "!");

        x = 1;

        x--;

        System.out.println("Instead of x = x - 1, use x++: " + x + "!");

            //PEMDAS
                    //Paranthesis
                    //Exponents
                    //Multiplication
                    //Division
                    //Addition
                    //Substraction

        System.out.println("Always remember PEMDAS!");





    }
}
